import pandas as pd


def run_test(df: pd.DataFrame) -> pd.DataFrame:
    """
    Classifies posting lines according to the delay between
    document_date and entered_date.

    Categories:
        1 = Promptly:       0 to less than 10 days
        2 = Delayed:       10 to less than 30 days
        3 = Very delayed:  30 days or more

    Uses posting_delay_days generated by posting_timeliness.py.

    Returns:
        DataFrame containing source_row_id and promptly.
    """

    required_columns = [
        "source_row_id",
        "posting_delay_days",
    ]

    missing_columns = [
        column for column in required_columns
        if column not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            f"Missing required columns: {missing_columns}"
        )

    delays = pd.to_numeric(
        df["posting_delay_days"],
        errors="coerce"
    )

    if delays.isna().any() or not delays.map(
        lambda value: pd.notna(value) and abs(value) != float("inf")
    ).all():
        raise ValueError(
            "Cannot classify promptly: posting_delay_days "
            "contains missing or invalid values."
        )

    promptly = pd.Series(
        1,
        index=df.index,
        dtype="int64"
    )

    promptly.loc[delays >= 10] = 2
    promptly.loc[delays >= 30] = 3

    return pd.DataFrame({
        "source_row_id": df["source_row_id"],
        "promptly": promptly
    })